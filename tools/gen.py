#!/usr/bin/env python3
# Generates src/tramp.S (exported vk* trampolines) and src/names.inc from tools/names.txt
import os
d=os.path.dirname(os.path.abspath(__file__))
names=[l.strip() for l in open(os.path.join(d,"names.txt")) if l.strip().startswith("vk")]
names=sorted(set(names))
with open(os.path.join(d,"..","src","names.inc"),"w") as f:
    f.write("#define VKSHIM_COUNT %d\n"%len(names))
    f.write("static const char* const kNames[VKSHIM_COUNT]={\n")
    for n in names: f.write("\"%s\",\n"%n)
    f.write("};\n")
with open(os.path.join(d,"..","src","tramp.S"),"w") as f:
    f.write("// generated by tools/gen.py - do not edit\n.text\n.align 2\n")
    f.write(".macro T name, idx\n.globl \\name\n.type \\name,%function\n\\name:\n")
    f.write("  adrp x16, vkshim_tbl+(\\idx*8)\n  ldr x16, [x16, :lo12:vkshim_tbl+(\\idx*8)]\n  cbz x16, 1f\n  br x16\n")
    f.write("1:\n  mov w0, #\\idx\n  b vkshim_missing\n.endm\n")
    for i,n in enumerate(names): f.write("T %s, %d\n"%(n,i))
print(len(names),"names")
