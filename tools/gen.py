#!/usr/bin/env python3
# Generates src/tramp.S (exported vk* trampolines) and src/names.inc from tools/names.txt
import os
d=os.path.dirname(os.path.abspath(__file__))
names=[l.strip() for l in open(os.path.join(d,"names.txt")) if l.strip().startswith("vk")]
names=sorted(set(names))
with open(os.path.join(d,"..","src","names.inc"),"w") as f:
    f.write("#define VKSHIM_COUNT %d\n"%len(names))
    f.write("static const char* const kNames[VKSHIM_COUNT]={\n")
    for n in names: f.write("\"%s\",\n"%n)
    f.write("};\n")
with open(os.path.join(d,"..","src","tramp.S"),"w") as f:
    f.write("// generated by tools/gen.py - do not edit\n.text\n.align 2\n")
    # slow path: x16 = export index. Saves argument registers, asks C++ for the target, tail-calls it.
    f.write(""".globl vkshim_ret0
.hidden vkshim_ret0
.type vkshim_ret0,%function
vkshim_ret0:
  mov x0, #0
  ret
.globl vkshim_slow
.hidden vkshim_slow
.type vkshim_slow,%function
vkshim_slow:
  stp x29, x30, [sp, #-240]!
  mov x29, sp
  stp x0, x1, [sp, #16]
  stp x2, x3, [sp, #32]
  stp x4, x5, [sp, #48]
  stp x6, x7, [sp, #64]
  str x8, [sp, #80]
  stp q0, q1, [sp, #96]
  stp q2, q3, [sp, #128]
  stp q4, q5, [sp, #160]
  stp q6, q7, [sp, #192]
  mov w0, w16
  bl vkshim_resolve
  mov x16, x0
  ldp x0, x1, [sp, #16]
  ldp x2, x3, [sp, #32]
  ldp x4, x5, [sp, #48]
  ldp x6, x7, [sp, #64]
  ldr x8, [sp, #80]
  ldp q0, q1, [sp, #96]
  ldp q2, q3, [sp, #128]
  ldp q4, q5, [sp, #160]
  ldp q6, q7, [sp, #192]
  ldp x29, x30, [sp], #240
  br x16
""")
    f.write(".macro T name, idx\n.globl \\name\n.type \\name,%function\n\\name:\n")
    f.write("  adrp x16, vkshim_tbl+(\\idx*8)\n  ldr x16, [x16, :lo12:vkshim_tbl+(\\idx*8)]\n  cbz x16, 1f\n  br x16\n")
    f.write("1:\n  mov w16, #\\idx\n  b vkshim_slow\n.endm\n")
    for i,n in enumerate(names): f.write("T %s, %d\n"%(n,i))
print(len(names),"names")
